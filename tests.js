const assert = require('node:assert/strict');
const c=require('./logic.js');
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`Expected ${b}, received ${a}`);
const bol=c.bolus(70,2,'mg/kg',10,'mg/mL');
close(bol.totalMg,140);close(bol.volumeMl,14);
const fent=c.bolus(70,2,'mcg/kg',50,'mcg/mL');
close(fent.totalMcg,140);close(fent.volumeMl,2.8);
const infusion=c.infusion(4,'mg',50,0.1,'mcg/kg/min',70);
close(infusion.mlPerHour,5.25);close(infusion.concMcgPerMl,80);
close(c.reverseInfusion(4,'mg',50,5.25,70),0.1);
close(c.infusion(200,'mg',20,4,'mg/kg/h',70).mlPerHour,28);
close(c.infusion(1000,'mcg',50,10,'mcg/min',70).mlPerHour,30);
const mix=c.mixing(4,1,50);
close(mix.stockMl,4);close(mix.diluentMl,46);close(mix.finalMgPerMl,0.08);
assert.ok(c.mixing(60,1,50).error);
assert.equal(c.bolus(70,2,'mg/kg',0,'mg/mL'),null);
assert.equal(c.infusion(4,'mg',50,.1,'mcg/kg/min',NaN),null);
const vit=c.vitals(70,170,120,80,80);
close(vit.bmi,70/2.89);close(vit.map,280/3);close(vit.shock,2/3);
assert.ok(c.vitals(70,170,80,120,80).invalidBp);
console.log('✓ Đã vượt qua 16 nhóm kiểm tra phép tính cơ bản.');
