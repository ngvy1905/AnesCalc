/* Run: node inhaled-tests.js */
const assert=require('node:assert/strict');
const c=require('./inhaled.js');
const approx=(actual,expected,tol=1e-8)=>assert.ok(Math.abs(actual-expected)<tol,'Expected '+expected+', got '+actual);
assert.equal(c.AGENTS.length,6);
assert.equal(c.findAgent('sevoflurane').svp,160);
assert.equal(c.findAgent('isoflurane').bloodGas,1.46);
assert.equal(c.findAgent('invalid'),null);
const sevo=c.saturatedChamber('sevoflurane',760,3,200);
approx(sevo.ratio,160/600);
approx(sevo.agentVaporMlMin,200*160/600);
approx(sevo.outputPct,100*(200*160/600)/(3000+200*160/600));
approx(sevo.saturatedPct,100*160/760);
approx(sevo.bypassMlMin,2800);
const iso=c.saturatedChamber('isoflurane',760,3,200);
approx(iso.ratio,240/520);
assert.ok(iso.outputPct>sevo.outputPct);
assert.match(c.saturatedChamber('desflurane',760,3,200).error,/không áp dụng/);
assert.match(c.saturatedChamber('nitrous',760,3,200).error,/không áp dụng/);
assert.ok(c.saturatedChamber('sevoflurane',160,3,200).error);
assert.ok(c.saturatedChamber('sevoflurane',0,3,200).error);
assert.ok(c.saturatedChamber('sevoflurane',760,0,200).error);
assert.ok(c.saturatedChamber('sevoflurane',760,3,3001).error);
assert.ok(c.saturatedChamber('sevoflurane',760,3,NaN).error);
const alt=c.desfluraneAltitude(6,380);
approx(alt.equivalentPct,12);
approx(alt.referencePartialMmHg,45.6);
approx(alt.ambientPartialMmHg,45.6);
approx(c.desfluraneAltitude(6,760).equivalentPct,6);
assert.ok(c.desfluraneAltitude(6,0).error);
assert.ok(c.desfluraneAltitude(100,760).error);
assert.ok(c.desfluraneAltitude(6,1).error);
console.log('✓ Inhaled anesthetics mathematical assertions passed.');
